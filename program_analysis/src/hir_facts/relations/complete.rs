//! Complete may-generated equation sites, independent of any satisfying assignment.

use std::collections::BTreeSet;

use abstract_interpretation::graph::{FlowGraph, NodeId};
use abstract_interpretation::solver::{CertifiedFacts, SolveResult};

use crate::hir_cfg::{CfgNodeKind, Origin};
use crate::hir_facts::forward::ForwardState;
use crate::hir_facts::relations::NormalizedEquation;
use crate::hir_facts::{AccessKey, AnalysisFacts, Fact, FactBlocker};
use crate::interprocedural::{ContextEvidence, ValidatedComponentPorts};

#[derive(Debug)]
pub(crate) struct GeneratedConstraintSite<'a> {
    site: NodeId,
    origin: Origin,
    equation: &'a NormalizedEquation,
}

/// All source-owned equations that may be generated by this bound local analysis.
///
/// This preserves conditional equations absent from the exit must intersection.
/// It does not select generation control or certify satisfiability or source readiness.
#[derive(Debug)]
pub(crate) struct GeneratedEquationSites<'a> {
    evidence: &'a ContextEvidence,
    sites: Vec<GeneratedConstraintSite<'a>>,
    keys: BTreeSet<AccessKey>,
}

impl GeneratedConstraintSite<'_> {
    pub(crate) const fn site(&self) -> NodeId {
        self.site
    }

    pub(crate) const fn origin(&self) -> Origin {
        self.origin
    }

    pub(crate) fn equation(&self) -> &NormalizedEquation {
        self.equation
    }
}

impl GeneratedEquationSites<'_> {
    pub(crate) fn evidence(&self) -> &ContextEvidence {
        self.evidence
    }

    pub(crate) fn sites(&self) -> &[GeneratedConstraintSite<'_>] {
        &self.sites
    }

    pub(crate) fn keys(&self) -> &BTreeSet<AccessKey> {
        &self.keys
    }
}

/// A single resource allowance shared by collection and both candidate checks.
pub(crate) struct ProofBudget {
    sites: usize,
    terms: usize,
    keys: usize,
    key_limit: usize,
    operations: usize,
}

impl Default for ProofBudget {
    fn default() -> Self {
        Self::limited(4096, 262_144, 4096, 1_048_576)
    }
}

impl ProofBudget {
    pub(crate) fn limited(sites: usize, terms: usize, keys: usize, operations: usize) -> Self {
        Self { sites, terms, keys, key_limit: keys, operations }
    }

    pub(crate) fn reserve_control_step(&mut self) -> bool {
        charge(&mut self.operations, 1)
    }

    fn reserve_site(&mut self, equation: &NormalizedEquation) -> bool {
        let Some(support_bound) = equation.term_count().checked_mul(2) else { return false };
        support_bound <= self.key_limit
            && charge(&mut self.sites, 1)
            && charge(&mut self.terms, equation.term_count())
    }

    pub(crate) fn reserve_key(&mut self) -> bool {
        charge(&mut self.keys, 1)
    }

    pub(crate) fn reserve_evaluation(&mut self, equation: &NormalizedEquation) -> bool {
        charge(&mut self.operations, equation.term_count())
    }
}

fn charge(remaining: &mut usize, amount: usize) -> bool {
    let Some(rest) = remaining.checked_sub(amount) else { return false };
    *remaining = rest;
    true
}

impl AnalysisFacts<'_> {
    /// Collect every normalized generated site from complete, source-owned facts.
    ///
    /// Source validity of each equation is checked before its normalized support.
    /// Unresolved generation control is retained as may-sites, never intersected away.
    pub(crate) fn generated_equation_sites(
        &self,
        budget: &mut ProofBudget,
    ) -> Fact<GeneratedEquationSites<'_>> {
        self.generated_sites_for(budget, None)
    }

    pub(crate) fn generated_component_equation_sites(
        &self,
        budget: &mut ProofBudget,
        ports: &ValidatedComponentPorts,
    ) -> Fact<GeneratedEquationSites<'_>> {
        self.generated_sites_for(budget, Some(ports))
    }

    fn generated_sites_for(
        &self,
        budget: &mut ProofBudget,
        ports: Option<&ValidatedComponentPorts>,
    ) -> Fact<GeneratedEquationSites<'_>> {
        match self.collect_generated_sites(budget, ports) {
            Ok(sites) => Fact::known(sites),
            Err(blockers) => Fact::blocked(blockers),
        }
    }

    fn collect_generated_sites(
        &self,
        budget: &mut ProofBudget,
        ports: Option<&ValidatedComponentPorts>,
    ) -> Result<GeneratedEquationSites<'_>, BTreeSet<FactBlocker>> {
        let Some(evidence) = &self.evidence_binding else {
            return Err(BTreeSet::from([FactBlocker::ForeignQuery]));
        };
        let facts = self.source_valid_forward(ports)?;
        let Some(exit) = facts.get(&self.cfg.exit()).and_then(|item| item.output.as_ref()) else {
            return Err(BTreeSet::from([FactBlocker::MissingExit]));
        };
        let Some((expected, _)) = exit.constraints() else {
            return Err(BTreeSet::from([FactBlocker::MissingExit]));
        };
        let mut result =
            GeneratedEquationSites { evidence, sites: Vec::new(), keys: BTreeSet::new() };
        for id in self.cfg.nodes() {
            if !budget.reserve_control_step() {
                return Err(BTreeSet::from([FactBlocker::Budget(*id)]));
            }
            if let Some(site) = self.generated_site(*id, facts)? {
                result.insert(site, budget)?;
            }
        }
        let collected: BTreeSet<_> = result.sites.iter().map(|site| site.site).collect();
        if collected != *expected {
            return Err(BTreeSet::from([FactBlocker::UnsupportedRelation(self.cfg.exit())]));
        }
        Ok(result)
    }

    fn source_valid_forward(
        &self,
        ports: Option<&ValidatedComponentPorts>,
    ) -> Result<&CertifiedFacts<NodeId, ForwardState>, BTreeSet<FactBlocker>> {
        let SolveResult::Complete(facts) = &self.forward else {
            return Err(self.forward_completion_blockers());
        };
        let validity = match ports {
            Some(ports) => self.generated_constraints_valid_with(ports),
            None => self.generated_constraints_valid(),
        };
        if let Some(blockers) = validity.unavailable() {
            return Err(blockers.clone());
        }
        Ok(facts)
    }

    fn generated_site<'a>(
        &self,
        id: NodeId,
        facts: &'a CertifiedFacts<NodeId, ForwardState>,
    ) -> Result<Option<GeneratedConstraintSite<'a>>, BTreeSet<FactBlocker>> {
        let Some(input) = facts.get(&id).and_then(|item| item.input.as_ref()) else {
            return Ok(None);
        };
        if input.variables().is_none() {
            return Ok(None);
        }
        let Some(node) = self.cfg.node(id) else {
            return Err(BTreeSet::from([FactBlocker::ForeignQuery]));
        };
        let CfgNodeKind::Constraint { .. } = &node.kind else { return Ok(None) };
        let output = facts.get(&id).and_then(|item| item.output.as_ref());
        let equation = output.and_then(|state| state.must_equations().equation_at_origin(id));
        let Some(equation) = equation else {
            return Err(BTreeSet::from([FactBlocker::UnsupportedRelation(id)]));
        };
        let Some(origin) = node.origin else {
            return Err(BTreeSet::from([FactBlocker::ForeignQuery]));
        };
        Ok(Some(GeneratedConstraintSite { site: id, origin, equation }))
    }
}

impl<'a> GeneratedEquationSites<'a> {
    fn insert(
        &mut self,
        entry: GeneratedConstraintSite<'a>,
        budget: &mut ProofBudget,
    ) -> Result<(), BTreeSet<FactBlocker>> {
        let GeneratedConstraintSite { site, equation, .. } = &entry;
        if !budget.reserve_site(equation) {
            return Err(BTreeSet::from([FactBlocker::Budget(*site)]));
        }
        for key in equation.accesses() {
            if !self.keys.contains(key) {
                if !budget.reserve_key() {
                    return Err(BTreeSet::from([FactBlocker::Budget(*site)]));
                }
                self.keys.insert(key.clone());
            }
        }
        self.sites.push(entry);
        Ok(())
    }
}

